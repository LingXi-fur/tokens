#!/usr/bin/env python3
"""Regenerate ui/world/assets/textures.js from the original CC0 jpgs.

Stdlib only. Run from anywhere; paths resolve relative to this file.
Output is deterministic: same inputs -> byte-identical module.
Sources: Poly Haven CC0 (see manifest.json). No network access here.
"""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MANIFEST = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))

SET_EXPORT = {"rock": "ROCK_CLIFF", "ground": "GROUND_ROCKY"}

def data_uri(path: Path) -> str:
    return "data:image/jpeg;base64," + base64.b64encode(path.read_bytes()).decode("ascii")

def main() -> None:
    chunks = [
        "// Generated by ui/world/assets/generate.py from Poly Haven CC0 originals.",
        "// License: CC0 1.0 Universal (https://polyhaven.com/license). Do not edit by hand;",
        "// rerun the generator instead. Metadata mirrors manifest.json for offline checks.",
    ]
    sources = []
    for set_key, export in SET_EXPORT.items():
        info = MANIFEST["sets"][set_key]
        maps = {name: data_uri(ROOT / m["file"]) for name, m in info["maps"].items()}
        chunks.append(f"export const {export} = {{")
        for name, uri in maps.items():
            chunks.append(f"  {name}: {json.dumps(uri)},")
        chunks.append("};")
        entry = {
            "export": export,
            "asset": info["asset"],
            "source": info["source"],
            "authors": info["authors"],
            "license": MANIFEST["license"],
            "maps": {n: {k: m[k] for k in ("file", "sha256", "bytes", "width", "height", "channels")} for n, m in info["maps"].items()},
        }
        sources.append(entry)
    chunks.append("export const ASSET_SOURCES = " + json.dumps(sources, indent=2) + ";")
    target = ROOT / "textures.js"
    target.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    total = sum(m["bytes"] for s in MANIFEST["sets"].values() for m in s["maps"].values())
    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    print(f"textures.js bytes={target.stat().st_size} source-jpg-bytes={total} sha256={digest}")

if __name__ == "__main__":
    main()
